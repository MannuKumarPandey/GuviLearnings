package Day2;

public class PrimitiveDataTypes {
    public static void main(String[] args) {

        //fundamnetal data types
        //1: Integaral :
        byte a = 100; // 8 bits  //primitive data types
        byte age = 30;  //primitive data types
        Byte aaa = 127; // 8 bits : Wrapper class of primitive data types
        System.out.println(Byte.MIN_VALUE);
        byte v= -128;
        System.out.println(Byte.MAX_VALUE);
        System.out.println(Byte.SIZE);

        short b = 32767; //16 bits//primitive data types
        Short bb = 32767;//Wrapper class of primitive data types
        System.out.println(Short.MIN_VALUE);
        System.out.println(Short.MAX_VALUE);
        System.out.println(Short.SIZE);

        int c = 3000; //32 bits//primitive data types
        Integer tt = 30000;//Wrapper class of primitive data types
        System.out.println(Integer.MIN_VALUE);
        System.out.println(Integer.MAX_VALUE);
        System.out.println(Integer.SIZE);

        long d = 40000; //64 bits//primitive data types
        long age2 = 25;//primitive data types
        Long ll = 444444l;//Wrapper class of primitive data types
        System.out.println(Long.MIN_VALUE);
        System.out.println(Long.MAX_VALUE);
        System.out.println(Long.SIZE);

        //decimal
        float f= 100.5f; //32 bits//primitive data types
        Float fff= 5555.6f;//Wrapper class of primitive data types
        System.out.println(Float.MIN_VALUE);
        System.out.println(Float.MAX_VALUE);
        System.out.println(Float.SIZE);

        double dd = 200.7; //64 bits//primitive data types
        double dd1 = 200777777.7d;//primitive data types
        Double ffff= 4000.7;//Wrapper class of primitive data types
        System.out.println(Double.MIN_VALUE);
        System.out.println(Double.MAX_VALUE);
        System.out.println(Double.SIZE);

        char p = 'r';//primitive data types
        Character ccc= 'h';//Wrapper class of primitive data types
        System.out.println(Character.SIZE);

        boolean bb6 = true;//primitive data types
        Boolean fffff= false;//Wrapper class of primitive data types+
        //System.out.println(Boolean.SIZE);


        //Note :-  can primitivge data types will store null as value
        //int cc = null;
        Integer cccgggg = null;




    }
}
