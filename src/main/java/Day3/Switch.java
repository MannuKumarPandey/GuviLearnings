package Day3;

public class Switch {
    public static void main(String[] args) {
        int p = 100;

        switch(p){

            case 100:
                System.out.println("100");
                break;


            case 200:
                System.out.println(200);
                break;

            case 300:
                System.out.println(300);
                break;


            case 400:
                System.out.println(400);
                break;


            default:
                System.out.println("rest all values !!!!!!!!!");
                break;


        }



    }
}
